// Variabler er en måte å lagre data i JavaScript

let age = 25; // Her lagrer vi tallet 25 i variabelen age
let name = "Ola"; // Her lagrer vi teksten "Ola" i variabelen name



// Const er en måte å lagre variabler som ikke skal endres

const birthYear = 1998; // Her lagrer vi tallet 1998 i variabelen birthYear
const pi = 3.14; // Her lagrer vi tallet 3.14 i variabelen pi



console.log(age); // Skriver ut verdien av variabelen age
console.log(name); // Skriver ut verdien av variabelen name


console.log(birthYear); // Skriver ut verdien av variabelen birthYear
console.log(pi); // Skriver ut verdien av variabelen pi